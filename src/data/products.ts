export const getProductBySlug = (slug: string) => products.find((p) => p.slug === slug)
export const getProductById = (id: string) => products.find((p) => p.id === id)
export const getProductsBySlugs = (slugs: string[]) =>
  slugs.map((s) => getProductBySlug(s)).filter((p): p is Product => Boolean(p))
export const getCollectionProducts = (collectionSlug: string) =>
  products.filter((p) => p.collections.includes(collectionSlug))
export const getRelatedProducts = (product: Product, limit = 4) => {
  const same = products.filter((p) => p.id !== product.id && p.category === product.category)
  const shared = products.filter(
    (p) => p.id !== product.id && p.category !== product.category && p.collections.some((c) => product.collections.includes(c)),
  )
  return [...same, ...shared].slice(0, limit)
}
export const isSingleSize = (p: Product) => p.sizes.length === 1
export const availableSizes = (p: Product) => p.sizes.filter((s) => !p.soldOutSizes?.includes(s))
